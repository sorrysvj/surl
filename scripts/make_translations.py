"""Generate the installer's custom-message files.

Inno Setup reads .isl files as UTF-8 only when they carry a byte-order mark,
and expects CRLF line endings. Editors disagree about both, and a mangled .isl
shows up as garbled text in the installer rather than as a build error - so the
files are generated here instead of being hand-maintained.

To add a language: copy the ENGLISH dict, translate the values, add it to
LANGUAGES below, and add one line to the [Languages] section of surl.iss.

Usage:  python scripts/make_translations.py
"""

