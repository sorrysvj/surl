# Inno Setup's LanguageName must be written as <hhhh> Unicode escapes so the
# language dialog renders correctly before a codepage is chosen.
def unicode_escape_name(name: str) -> str:
    return "".join("<%04X>" % ord(ch) for ch in name)


LANGUAGES = [
    # (file name, comment language, LanguageName, LanguageID, strings)
    ("surl.en.isl", "English", "English", "0409", ENGLISH),
    ("surl.ru.isl", "Russian", unicode_escape_name("Русский"), "0419", RUSSIAN),
]


def render(language: str, language_name: str, language_id: str,
           strings: "dict[str, str]") -> str:
    missing = set(ENGLISH) - set(strings)
    if missing:
        raise SystemExit(
            "%s is missing translations for: %s" % (language, ", ".join(sorted(missing)))
        )

    out = HEADER.format(
        language=language, language_name=language_name, language_id=language_id
    )
    for title, keys in SECTIONS:
        out += "\n; --- %s %s\n" % (title, "-" * max(3, 60 - len(title)))
        for key in keys:
            out += "%s=%s\n" % (key, strings[key])
    return out


def main() -> None:
    os.makedirs(OUT_DIR, exist_ok=True)
    for file_name, language, language_name, language_id, strings in LANGUAGES:
        text = render(language, language_name, language_id, strings)
        path = os.path.join(OUT_DIR, file_name)
        # UTF-8 with BOM and CRLF: what Inno Setup requires.
        with io.open(path, "w", encoding="utf-8-sig", newline="\r\n") as handle:
            handle.write(text)
        print("wrote %s (%d bytes)" % (path, os.path.getsize(path)))


if __name__ == "__main__":
    main()
